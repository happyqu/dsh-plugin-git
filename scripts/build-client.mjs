/** Bundle local modules inside DSH's classic client-loader factory. */
import { build } from 'esbuild'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const manifest = JSON.parse(await readFile(new URL('package.json', root), 'utf8'))
const result = await build({
  absWorkingDir: fileURLToPath(root),
  entryPoints: ['lib/client.js'],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  external: ['react', 'react-dom', '@deepseek-ai/dsh-client-ui-primitives'],
  charset: 'utf8',
  legalComments: 'inline',
})
const output = `// Generated by npm run build; edit lib/client/ sources instead.
window.__ModuleLoader__.load({
  id: '${manifest.name}',
  factory: (require) => {
    var module = { exports: {} }, exports = module.exports
${result.outputFiles[0].text}
    return module.exports
  },
})
`
await mkdir(new URL('dist/', root), { recursive: true })
await writeFile(new URL('dist/client.js', root), output, 'utf8')
console.log('Built standalone DSH client')
